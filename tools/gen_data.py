#!/usr/bin/env python3
"""Generate apworld/rs64/data.py and client/src/generated/rs64ap_data.h from data/rs64ap.json.

Usage:
    python tools/gen_data.py          write both files
    python tools/gen_data.py --check  exit 1 if a generated file is stale (for CI)

It also copies SETUP.md to apworld/rs64/docs/setup_en.md, and the README's gameplay sections to the apworld's
game page.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "rs64ap.json"
PY_OUT = ROOT / "apworld" / "rs64" / "data.py"
H_OUT = ROOT / "client" / "src" / "generated" / "rs64ap_data.h"

# Location slots within a mission (docs/BIBLE.md 9.2).
SLOT_COMPLETE = 0
SLOT_MEDAL = {1: "Bronze Medal", 2: "Silver Medal", 3: "Gold Medal"}
SLOT_PICKUP = 10
SLOT_OBJECTIVE0 = 20


def item_ids(d: dict) -> dict[str, int]:
    base = d["id_base"]
    ids: dict[str, int] = {}
    for m in d["missions"]:
        ids[f"{m['name']} Pass"] = base + m["id"] + 1
    for s in d["ships"]:
        ids[s["name"]] = base + 101 + s["craft"]
    for u in d["upgrades"]:
        ids[u["name"]] = base + 201 + u["bit"] - 9
    for f in d["filler"]:
        ids[f["name"]] = base + 300 + f["index"]
    for e in d["extras"]:
        ids[e["name"]] = base + 250 + e["index"]
    for m in d["missions"]:
        ids[f"{m['name']} Medal Leniency"] = base + 400 + m["id"]
    return ids


def location_ids(d: dict) -> dict[str, int]:
    base = d["id_base"]
    ids: dict[str, int] = {}
    for m in d["missions"]:
        lb = base + m["id"] * 100
        ids[f"{m['name']} - Complete"] = lb + SLOT_COMPLETE
        for tier, label in SLOT_MEDAL.items():
            ids[f"{m['name']} - {label}"] = lb + tier
        if m["pickup"]:
            ids[f"{m['name']} - Upgrade Pickup"] = lb + SLOT_PICKUP
        for n in range(1, d["max_objectives_per_mission"] + 1):
            ids[f"{m['name']} - Objective {n}"] = lb + SLOT_OBJECTIVE0 + n - 1
    return ids


def check(d: dict) -> None:
    names = {s["name"] for s in d["ships"]}
    for m in d["missions"]:
        assert 0 <= m["id"] <= 18, m
        assert m["kind"] in ("campaign", "final", "bonus"), m
        assert m["default_ship"] in names, f"{m['name']}: unknown default ship"
        for s in m["replay_ships"]:
            assert s in names and s != m["default_ship"], f"{m['name']}: bad replay ship {s}"
        obj = m["objectives"]
        assert obj is None or 0 <= obj <= d["max_objectives_per_mission"], m
    assert [m["id"] for m in d["missions"]] == list(range(19))
    assert [s["craft"] for s in d["ships"]] == list(range(9))
    assert [u["bit"] for u in d["upgrades"]] == list(range(9, 17))
    for table in (item_ids(d), location_ids(d)):
        assert len(set(table.values())) == len(table), "duplicate id"


def py_source(d: dict) -> str:
    out = [
        "# Generated by tools/gen_data.py from data/rs64ap.json. Do not edit.",
        "from typing import Any",
        "",
        f"GAME: str = {d['game']!r}",
        f"WORLD_VERSION: str = {d['world_version']!r}",
        f"ID_BASE: int = {d['id_base']}",
        f"VERIFIED: dict[str, bool] = {({k: v for k, v in d['verified'].items() if not k.startswith('//')})!r}",
        f"MAX_OBJECTIVES: int = {d['max_objectives_per_mission']}",
        "",
        "MISSIONS: list[dict[str, Any]] = [",
    ]
    for m in d["missions"]:
        out.append(f"    {m!r},")
    out += ["]", "", "SHIPS: list[dict[str, Any]] = ["]
    for s in d["ships"]:
        out.append(f"    {s!r},")
    out += ["]", "", "UPGRADES: list[dict[str, Any]] = ["]
    for u in d["upgrades"]:
        out.append(f"    {u!r},")
    out += ["]", "", "FILLER: list[dict[str, Any]] = ["]
    for f in d["filler"]:
        out.append(f"    {f!r},")
    out += ["]", "", "EXTRAS: list[dict[str, Any]] = ["]
    for e in d["extras"]:
        out.append(f"    {({k: v for k, v in e.items() if not k.startswith('//')})!r},")
    out += ["]", "", f"LENIENCY: list[str] = {[m['name'] + ' Medal Leniency' for m in d['missions']]!r}",
            "", "ITEM_IDS: dict[str, int] = {"]
    for k, v in item_ids(d).items():
        out.append(f"    {k!r}: {v},")
    out += ["}", "", "LOCATION_IDS: dict[str, int] = {"]
    for k, v in location_ids(d).items():
        out.append(f"    {k!r}: {v},")
    out += ["}", ""]
    return "\n".join(out)


def c_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def h_source(d: dict) -> str:
    ms = d["missions"]
    craft_of = {s["name"]: s["craft"] for s in d["ships"]}
    kind = {"campaign": 0, "final": 1, "bonus": 2}
    lines = [
        "// Generated by tools/gen_data.py from data/rs64ap.json. Do not edit.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace rs64ap::data {",
        "",
        f"constexpr const char* kGame = {c_str(d['game'])};",
        f"constexpr const char* kWorldVersion = {c_str(d['world_version'])};",
        f"constexpr int64_t kIdBase = {d['id_base']};",
        "constexpr int kMissionCount = 19;",
        "constexpr int kShipCount = 9;",
        "constexpr int kUpgradeCount = 8;",
        f"constexpr int kFillerCount = {len(d['filler'])};",
        f"constexpr int kMaxObjectives = {d['max_objectives_per_mission']};",
        f"constexpr float kRegenSeconds = {float(d['regen_seconds'])}f;",
        f"constexpr float kInvincibilitySeconds = {float(d['invincibility_seconds'])}f;",
        f"constexpr float kLeniencyTimeScale = {float(d['leniency']['time_scale'])}f;",
        f"constexpr float kLeniencyNeedScale = {float(d['leniency']['need_scale'])}f;",
        "",
        "// Location slots within a mission: id = kIdBase + level * 100 + slot.",
        f"constexpr int kSlotComplete = {SLOT_COMPLETE};",
        "constexpr int kSlotBronze = 1, kSlotSilver = 2, kSlotGold = 3;",
        f"constexpr int kSlotPickup = {SLOT_PICKUP};",
        f"constexpr int kSlotObjective0 = {SLOT_OBJECTIVE0};",
        "",
        "constexpr int64_t location_id(int level, int slot) { return kIdBase + level * 100 + slot; }",
        "constexpr int64_t pass_item(int level) { return kIdBase + level + 1; }",
        "constexpr int64_t ship_item(int craft) { return kIdBase + 101 + craft; }",
        "constexpr int64_t upgrade_item(int bit) { return kIdBase + 201 + bit - 9; }",
        "constexpr int64_t filler_item(int index) { return kIdBase + 300 + index; }",
        "constexpr int64_t extra_item(int index) { return kIdBase + 250 + index; }",
        "constexpr int64_t leniency_item(int level) { return kIdBase + 400 + level; }",
        "constexpr int kExtraReplenishingSecondaries = 1;",
        "",
        "// 0 campaign, 1 final (campaign), 2 bonus.",
        "constexpr int kMissionKind[kMissionCount] = {" + ", ".join(str(kind[m["kind"]]) for m in ms) + "};",
        "constexpr bool kMissionPickup[kMissionCount] = {" + ", ".join("true" if m["pickup"] else "false" for m in ms) + "};",
        "// Objectives per mission (objective n = flag bit n-1); 0 = unknown.",
        "constexpr int kObjectiveCount[kMissionCount] = {" + ", ".join(str(m["objectives"] or 0) for m in ms) + "};",
        "// Hangar mask bits (1 << craft) per mission: the default ship, and the ships vanilla adds after a completion.",
        "constexpr uint32_t kDefaultShip[kMissionCount] = {"
        + ", ".join(hex(1 << craft_of[m["default_ship"]]) for m in ms) + "};",
        "constexpr uint32_t kReplayShips[kMissionCount] = {"
        + ", ".join(hex(sum(1 << craft_of[s] for s in m["replay_ships"])) for m in ms) + "};",
        "constexpr const char* kMissionNames[kMissionCount] = {",
    ]
    lines += [f"    {c_str(m['name'])}," for m in ms]
    lines += ["};", "constexpr const char* kShipNames[kShipCount] = {"]
    lines += [f"    {c_str(s['name'])}," for s in d["ships"]]
    lines += ["};", "constexpr const char* kUpgradeNames[kUpgradeCount] = {"]
    lines += [f"    {c_str(u['name'])}," for u in d["upgrades"]]
    lines += ["};", "", "struct Filler { int index; const char* name; const char* effect; };",
              "constexpr Filler kFiller[kFillerCount] = {"]
    lines += [f"    {{{f['index']}, {c_str(f['name'])}, {c_str(f['effect'])}}}," for f in d["filler"]]
    lines += ["};", "", "}  // namespace rs64ap::data", ""]
    return "\n".join(lines)


def game_page() -> str:
    """The apworld's game page (shown by Archipelago): the README's gameplay sections, Goal to DeathLink."""
    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    start, end = readme.index("## Goal"), readme.index("## Known limitations")
    body = readme[start:end].rstrip() + "\n"
    return ("# Star Wars: Rogue Squadron\n\n"
            "Setup: [setup guide](https://github.com/Hinaloth/RS64AP/blob/main/SETUP.md).\n\n" + body)


def main() -> int:
    d = json.loads(SRC.read_text(encoding="utf-8"))
    check(d)
    outputs = {PY_OUT: py_source(d), H_OUT: h_source(d)}
    # The apworld's setup guide (shown by Archipelago) is a copy of the repo's SETUP.md.
    outputs[ROOT / "apworld" / "rs64" / "docs" / "setup_en.md"] = (ROOT / "SETUP.md").read_text(encoding="utf-8")
    outputs[ROOT / "apworld" / "rs64" / "docs" / "en_Star Wars Rogue Squadron.md"] = game_page()
    if "--check" in sys.argv:
        stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)} (run python tools/gen_data.py)")
        return 1 if stale else 0
    for p, text in outputs.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
